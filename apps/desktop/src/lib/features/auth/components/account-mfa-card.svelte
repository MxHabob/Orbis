<script lang="ts">
import { Card, CardHeader, CardTitle, CardContent } from "@orbis/ui/card";
import { Button } from "@orbis/ui/button";
import { Badge } from "@orbis/ui/badge";
import { ShieldCheck, ShieldAlert, Smartphone, CheckCircle2 } from "@lucide/svelte";
import MfaEnrollModal from "./mfa-enroll-modal.svelte";

interface Props {
  isMfaEnabled?: boolean;
  onRefresh?: () => void;
}

let { isMfaEnabled = false, onRefresh }: Props = $props();

let showEnrollModal = $state(false);
</script>

<Card class="border border-border/80 shadow-sm rounded-2xl overflow-hidden">
  <CardHeader class="bg-muted/40 px-6 py-4 border-b border-border/60">
    <div class="flex items-center justify-between">
      <div class="flex items-center gap-3">
        <div class="p-2 rounded-xl bg-primary/10 text-primary">
          <ShieldCheck size={20} class="stroke-[2.2]" />
        </div>
        <div>
          <CardTitle class="text-sm font-bold text-foreground">
            Two-Factor Authentication (2FA)
          </CardTitle>
          <p class="text-xs text-muted-foreground mt-0.5">
            Add an extra layer of security using an authenticator app (RFC 6238 TOTP).
          </p>
        </div>
      </div>
      
      {#if isMfaEnabled}
        <Badge variant="success" class="text-[10px] font-bold uppercase py-1 px-3 rounded-full flex items-center gap-1.5">
          <CheckCircle2 size={12} />
          <span>Active</span>
        </Badge>
      {:else}
        <Badge variant="secondary" class="text-[10px] font-bold uppercase py-1 px-3 rounded-full text-muted-foreground">
          Not Enabled
        </Badge>
      {/if}
    </div>
  </CardHeader>

  <CardContent class="p-6">
    <div class="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4">
      <div class="flex items-start gap-3">
        <div class="p-3 rounded-xl bg-muted/60 text-foreground border border-border/40">
          <Smartphone size={22} />
        </div>
        <div class="flex flex-col text-start gap-1">
          <span class="text-xs font-bold text-foreground">
            Authenticator App (Google Authenticator, Microsoft Authenticator)
          </span>
          <p class="text-xs text-muted-foreground max-w-lg leading-relaxed">
            {#if isMfaEnabled}
              Your account is secured with 2FA. Every login will require a 6-digit dynamic code generated by your authenticator app.
            {:else}
              We strongly recommend enabling 2FA to protect your account against unauthorized access, credential stuffing, and phishing.
            {/if}
          </p>
        </div>
      </div>

      <div class="shrink-0 w-full sm:w-auto">
        {#if isMfaEnabled}
          <Button
            variant="outline"
            size="sm"
            class="w-full sm:w-auto rounded-xl text-xs font-semibold gap-1.5 h-9"
            onclick={() => (showEnrollModal = true)}
          >
            <span>Reconfigure 2FA</span>
          </Button>
        {:else}
          <Button
            size="sm"
            class="w-full sm:w-auto rounded-xl text-xs font-bold gap-1.5 h-9 bg-primary text-primary-foreground shadow-sm"
            onclick={() => (showEnrollModal = true)}
          >
            <ShieldCheck size={15} />
            <span>Enable 2FA</span>
          </Button>
        {/if}
      </div>
    </div>
  </CardContent>
</Card>

<MfaEnrollModal
  bind:open={showEnrollModal}
  onSuccess={() => {
    isMfaEnabled = true;
    onRefresh?.();
  }}
  onClose={() => (showEnrollModal = false)}
/>
