<!--
  @component StepOrganization
  Step 3: Enriched Organization Profile & Regional Settings.
  Spacious 2-column layout for Arabic/English official names, educational track,
  capacity size, country, city, base currency, timezone, and calendar preferences.
  (Organization Code and Slug are automatically generated by the backend).
-->
<script lang="ts">
import * as m from "$lib/paraglide/messages";
import {
  type OnboardingFormModel,
  EDUCATIONAL_TRACK_OPTIONS,
  ORGANIZATION_SIZE_OPTIONS,
} from "../types";
import { Label } from "@orbis/ui/label";
import { Input } from "@orbis/ui/input";
import {
  Select,
  SelectTrigger,
  SelectContent,
  SelectItem,
} from "@orbis/ui/select";
import { BilingualNameFields } from "@orbis/ui/bilingual-name-fields";
import { Card, CardContent } from "@orbis/ui/card";
import { suggestLocalTranslation } from "$lib/shared/translation/local-engine";

let {
  form = $bindable<OnboardingFormModel>(),
  errors = {},
}: {
  form: OnboardingFormModel;
  errors?: Record<string, string>;
} = $props();

</script>

<div class="space-y-6 max-w-5xl mx-auto py-2">
  <div class="space-y-2 text-start">
    <p class="text-sm text-muted-foreground max-w-2xl leading-relaxed">
      {m.operations_ui_organization_setup_description()}
    </p>
  </div>

  <Card class="mx-auto max-w-3xl">
    <CardContent class="space-y-6 p-5 text-start sm:p-7">
      <BilingualNameFields
        arId="org-name-ar"
        enId="org-name-en"
        arLabel={m.ui_onboarding_organization_organization_name_arabic()}
        enLabel={m.ui_onboarding_organization_organization_name_english()}
        enRequired
        bind:arValue={form.organizationNameAr}
        bind:enValue={form.organizationName}
        arPlaceholder={m.operations_ui_organization_name_arabic_example()}
        enPlaceholder="e.g. Al-Noor Academy"
        arError={errors.organizationNameAr}
        enError={errors.organizationName}
        kind="label"
        requestSuggestion={suggestLocalTranslation}
        replaceUneditedInitialValues
        loadingMessage={m.bilingual_entry_loading()}
        failureMessage={m.bilingual_entry_failure()}
      />

      <div class="grid grid-cols-1 gap-4 sm:grid-cols-3">
        <div class="space-y-1.5">
          <Label for="org-country-name">{m.onboarding_org_country_name()}</Label>
          <Input id="org-country-name" bind:value={form.countryName} />
        </div>
        <div class="space-y-1.5">
          <Label for="org-ministry-name">{m.onboarding_org_ministry_name()}</Label>
          <Input id="org-ministry-name" bind:value={form.ministryName} />
        </div>
        <div class="space-y-1.5">
          <Label for="org-region-name">{m.onboarding_org_region_name()}</Label>
          <Input id="org-region-name" bind:value={form.regionName} />
        </div>
      </div>

      <div class="grid grid-cols-1 gap-5 sm:grid-cols-2">
      <div class="space-y-1.5">
        <Label class="text-xs font-medium text-foreground">
          {m.ui_onboarding_organization_educational_track()}
        </Label>
        <Select
          type="single"
          value={form.educationalTrack}
          onValueChange={(v) => (form.educationalTrack = v ?? "national")}
        >
          <SelectTrigger class="w-full h-9 text-xs">
            {EDUCATIONAL_TRACK_OPTIONS.find((t) => t.value === form.educationalTrack)?.label() || form.educationalTrack}
          </SelectTrigger>
          <SelectContent>
            {#each EDUCATIONAL_TRACK_OPTIONS as opt (opt.value)}
              <SelectItem value={opt.value}>
                <div class="space-y-0.5">
                  <div class="text-xs font-medium">{opt.label()}</div>
                </div>
              </SelectItem>
            {/each}
          </SelectContent>
        </Select>
      </div>

      <div class="space-y-1.5">
        <Label class="text-xs font-medium text-foreground">
          {m.ui_onboarding_organization_expected_student_capacity()}
        </Label>
        <Select
          type="single"
          value={form.organizationSize}
          onValueChange={(v) => (form.organizationSize = v ?? "medium")}
        >
          <SelectTrigger class="w-full h-9 text-xs">
            {ORGANIZATION_SIZE_OPTIONS.find((s) => s.value === form.organizationSize)?.label() || form.organizationSize}
          </SelectTrigger>
          <SelectContent>
            {#each ORGANIZATION_SIZE_OPTIONS as opt (opt.value)}
              <SelectItem value={opt.value}>
                <span class="text-xs">{opt.label()}</span>
              </SelectItem>
            {/each}
          </SelectContent>
        </Select>
      </div>
      </div>
    </CardContent>
  </Card>
</div>
