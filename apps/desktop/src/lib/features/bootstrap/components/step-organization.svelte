<!--
  @component StepOrganization
  Step 3: Enriched Organization Profile & Regional Settings.
  Spacious 2-column layout for Arabic/English official names, educational track,
  capacity size, country, city, base currency, timezone, and calendar preferences.
  (Organization Code and Slug are automatically generated by the backend).
-->
<script lang="ts">
import * as m from "$lib/paraglide/messages";
import { onMount } from "svelte";
import { api } from "$lib/api/client";
import {
  type OnboardingFormModel,
  TIMEZONE_OPTIONS,
  CURRENCY_OPTIONS,
  COUNTRIES_LIST,
  EDUCATIONAL_TRACK_OPTIONS,
  ORGANIZATION_SIZE_OPTIONS,
  COLOR_PRESETS,
  type CurrencyOption,
} from "../types";
import { Input } from "@orbis/ui/input";
import { Label } from "@orbis/ui/label";
import { Checkbox } from "@orbis/ui/checkbox";
import {
  Select,
  SelectTrigger,
  SelectContent,
  SelectItem,
} from "@orbis/ui/select";
import { Check } from "@orbis/icons";

let {
  form = $bindable<OnboardingFormModel>(),
  errors = {},
  isRTL = false,
}: {
  form: OnboardingFormModel;
  errors?: Record<string, string>;
  isRTL?: boolean;
} = $props();

let availableCurrencies = $state<CurrencyOption[]>(CURRENCY_OPTIONS);

onMount(async () => {
  try {
    const list = await api.listCurrencies();
    if (list && list.length > 0) {
      // Merge system currencies with default flags
      const mapped: CurrencyOption[] = list.map((c) => {
        const existing = CURRENCY_OPTIONS.find((opt) => opt.code === c.code);
        return {
          code: c.code,
          symbol: () => c.symbol || c.code,
          name: () => c.name || c.code,
          flag: existing?.flag || "🌐",
        };
      });
      availableCurrencies = mapped;
    }
  } catch {
    // Fallback to standard comprehensive ISO currency registry
    availableCurrencies = CURRENCY_OPTIONS;
  }
});

function selectCountry(countryCode: string) {
  form.countryCode = countryCode;
  const country = COUNTRIES_LIST.find((c) => c.code === countryCode);
  if (country) {
    if (country.defaultCurrency) form.baseCurrencyCode = country.defaultCurrency;
    if (country.defaultTimezone) form.timezone = country.defaultTimezone;
  }
}
</script>

<div class="space-y-6 max-w-5xl mx-auto py-2">
  <div class="space-y-2 text-start">
    <div class="flex items-center gap-2">
      <span class="text-xs font-semibold text-primary uppercase font-mono tracking-wider">
        {m.ui_onboarding_organization_step_3_of_6()}
      </span>
    </div>
    <h2 class="text-2xl font-bold tracking-tight text-foreground">
      {m.ui_onboarding_organization_organization_profile_identity()}
    </h2>
    <p class="text-sm text-muted-foreground max-w-2xl leading-relaxed">
      {m.operations_ui_organization_setup_description()}
    </p>
  </div>

  <div class="grid grid-cols-1 lg:grid-cols-2 gap-6 text-start">
    <!-- Left Card: Institution Identity & Track -->
    <div class="rounded-2xl border border-border/70 bg-card p-6 space-y-5 shadow-xs">
      <div class="border-b border-border/40 pb-3">
        <h3 class="text-sm font-bold text-foreground uppercase tracking-wider font-mono">
          {m.ui_onboarding_organization_identity_track()}
        </h3>
      </div>

      <!-- Arabic Name -->
      <div class="space-y-1.5">
        <Label for="org-name-ar" class="text-xs font-medium text-foreground">
          {m.ui_onboarding_organization_organization_name_arabic()}
        </Label>
        <Input
          id="org-name-ar"
          type="text"
          placeholder={m.operations_ui_organization_name_arabic_example()}
          bind:value={form.organizationNameAr}
          class="h-9 text-xs"
        />
        {#if errors.organizationNameAr}
          <p class="text-[11px] text-destructive">{errors.organizationNameAr}</p>
        {/if}
      </div>

      <!-- English Name -->
      <div class="space-y-1.5">
        <Label for="org-name-en" class="text-xs font-medium text-foreground">
          {m.ui_onboarding_organization_organization_name_english()}
        </Label>
        <Input
          id="org-name-en"
          type="text"
          placeholder="e.g. Al-Noor Academy"
          bind:value={form.organizationName}
          class="h-9 text-xs"
        />
        {#if errors.organizationName}
          <p class="text-[11px] text-destructive">{errors.organizationName}</p>
        {/if}
      </div>

      <!-- Educational Track -->
      <div class="space-y-1.5">
        <Label class="text-xs font-medium text-foreground">
          {m.ui_onboarding_organization_educational_track()}
        </Label>
        <Select
          type="single"
          value={form.educationalTrack}
          onValueChange={(v) => (form.educationalTrack = v ?? "national")}
        >
          <SelectTrigger class="w-full h-9 text-xs">
            {EDUCATIONAL_TRACK_OPTIONS.find((t) => t.value === form.educationalTrack)?.label() || form.educationalTrack}
          </SelectTrigger>
          <SelectContent>
            {#each EDUCATIONAL_TRACK_OPTIONS as opt}
              <SelectItem value={opt.value}>
                <div class="space-y-0.5">
                  <div class="text-xs font-medium">{opt.label()}</div>
                </div>
              </SelectItem>
            {/each}
          </SelectContent>
        </Select>
      </div>

      <!-- Capacity Size -->
      <div class="space-y-1.5">
        <Label class="text-xs font-medium text-foreground">
          {m.ui_onboarding_organization_expected_student_capacity()}
        </Label>
        <Select
          type="single"
          value={form.organizationSize}
          onValueChange={(v) => (form.organizationSize = v ?? "medium")}
        >
          <SelectTrigger class="w-full h-9 text-xs">
            {ORGANIZATION_SIZE_OPTIONS.find((s) => s.value === form.organizationSize)?.label() || form.organizationSize}
          </SelectTrigger>
          <SelectContent>
            {#each ORGANIZATION_SIZE_OPTIONS as opt}
              <SelectItem value={opt.value}>
                <span class="text-xs">{opt.label()}</span>
              </SelectItem>
            {/each}
          </SelectContent>
        </Select>
      </div>
    </div>

    <!-- Right Card: Regional & Fiscal Settings -->
    <div class="rounded-2xl border border-border/70 bg-card p-6 space-y-5 shadow-xs">
      <div class="border-b border-border/40 pb-3">
        <h3 class="text-sm font-bold text-foreground uppercase tracking-wider font-mono">
          {m.ui_onboarding_organization_regional_fiscal_parameters()}
        </h3>
      </div>

      <div class="grid grid-cols-1 sm:grid-cols-2 gap-4">
        <!-- Country -->
        <div class="space-y-1.5">
          <Label class="text-xs font-medium text-foreground">
            {m.ui_onboarding_organization_country_region()}
          </Label>
          <Select
            type="single"
            value={form.countryCode}
            onValueChange={(v) => v && selectCountry(v)}
          >
            <SelectTrigger class="w-full h-9 text-xs">
              {COUNTRIES_LIST.find((c) => c.code === form.countryCode) ? `${COUNTRIES_LIST.find((c) => c.code === form.countryCode)?.flag} ${COUNTRIES_LIST.find((c) => c.code === form.countryCode)?.name()}` : form.countryCode}
            </SelectTrigger>
            <SelectContent>
              {#each COUNTRIES_LIST as country}
                <SelectItem value={country.code}>
                  <span class="text-xs">{country.flag} {country.name()}</span>
                </SelectItem>
              {/each}
            </SelectContent>
          </Select>
        </div>

        <!-- City -->
        <div class="space-y-1.5">
          <Label for="org-city" class="text-xs font-medium text-foreground">
            {m.ui_onboarding_organization_city_campus()}
          </Label>
          <Input
            id="org-city"
            type="text"
            placeholder={m.ui_onboarding_organization_e_g_riyadh()}
            bind:value={form.city}
            class="h-9 text-xs"
          />
        </div>
      </div>

      <div class="grid grid-cols-1 sm:grid-cols-2 gap-4">
        <!-- Base Currency (Dynamic Table / Registry Sync) -->
        <div class="space-y-1.5">
          <Label class="text-xs font-medium text-foreground">
            {m.ui_onboarding_organization_base_currency()}
          </Label>
          <Select
            type="single"
            value={form.baseCurrencyCode}
            onValueChange={(v) => (form.baseCurrencyCode = v ?? "SAR")}
          >
            <SelectTrigger class="w-full h-9 text-xs font-mono">
              {form.baseCurrencyCode} ({availableCurrencies.find((c) => c.code === form.baseCurrencyCode)?.symbol() || form.baseCurrencyCode})
            </SelectTrigger>
            <SelectContent>
              {#each availableCurrencies as cur}
                <SelectItem value={cur.code}>
                  <span class="text-xs font-mono">{cur.flag} {cur.code} - {cur.name()}</span>
                </SelectItem>
              {/each}
            </SelectContent>
          </Select>
        </div>

        <!-- Timezone -->
        <div class="space-y-1.5">
          <Label class="text-xs font-medium text-foreground">
            {m.ui_onboarding_organization_timezone()}
          </Label>
          <Select
            type="single"
            value={form.timezone}
            onValueChange={(v) => (form.timezone = v ?? "Asia/Riyadh")}
          >
            <SelectTrigger class="w-full h-9 text-xs font-mono">
              {form.timezone}
            </SelectTrigger>
            <SelectContent>
              {#each TIMEZONE_OPTIONS as tz}
                <SelectItem value={tz.value}>
                  <span class="text-xs font-mono">{tz.label()} ({tz.offset})</span>
                </SelectItem>
              {/each}
            </SelectContent>
          </Select>
        </div>
      </div>

      <!-- Dual Hijri Preference -->
      <div class="p-3.5 rounded-xl bg-muted/20 border border-border/50 flex items-center justify-between">
        <div class="space-y-0.5">
          <Label for="hijri-toggle" class="text-xs font-semibold text-foreground cursor-pointer">
            {m.ui_onboarding_organization_dual_hijri_gregorian_calendar()}
          </Label>
          <p class="text-[11px] text-muted-foreground">
            {m.ui_onboarding_organization_display_corresponding_umm_al_qura_hijri_dates_across_modules()}
          </p>
        </div>
        <Checkbox id="hijri-toggle" bind:checked={form.isHijriEnabled} />
      </div>

      <!-- Theme Color Palette -->
      <div class="space-y-2 pt-1">
        <Label class="text-xs font-medium text-foreground">
          {m.ui_onboarding_organization_accent_color_theme()}
        </Label>
        <div class="flex items-center gap-2.5">
          {#each COLOR_PRESETS as color}
            {@const isColorActive = form.primaryColor === color.value}
            <button
              type="button"
              onclick={() => (form.primaryColor = color.value)}
              class="size-7 rounded-full transition-transform flex items-center justify-center {isColorActive ? 'scale-110 ring-2 ring-foreground ring-offset-2 ring-offset-background' : 'hover:scale-105'}"
              style="background-color: {color.value};"
              title={color.label()}
            >
              {#if isColorActive}
                <Check size={12} class="text-white" strokeWidth={3} />
              {/if}
            </button>
          {/each}
        </div>
      </div>
    </div>
  </div>
</div>
