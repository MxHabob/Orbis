<!--
  @component StepOrganization
  Step 3: Enriched Organization Profile & Smart Identity Configuration.
  Curriculum track selection, institution size, regional settings, contact details,
  licensing info, and brand theme customization (Slug is auto-generated by backend).
-->
<script lang="ts">
import {
  type OnboardingFormModel,
  TIMEZONE_OPTIONS,
  CURRENCY_OPTIONS,
  COUNTRIES_LIST,
  EDUCATIONAL_TRACK_OPTIONS,
  ORGANIZATION_SIZE_OPTIONS,
  COLOR_PRESETS,
} from "../types";
import { Input } from "@orbis/ui/input";
import { Label } from "@orbis/ui/label";
import { Checkbox } from "@orbis/ui/checkbox";
import { Card, CardContent } from "@orbis/ui/card";
import {
  Select,
  SelectTrigger,
  SelectContent,
  SelectItem,
} from "@orbis/ui/select";
import {
  Check,
  Tag,
  CreditCard,
  Clock,
} from "@orbis/icons";

let {
  form = $bindable<OnboardingFormModel>(),
  errors = {},
  isRTL = false,
}: {
  form: OnboardingFormModel;
  errors?: Record<string, string>;
  isRTL?: boolean;
} = $props();

function selectCountry(countryCode: string) {
  form.countryCode = countryCode;
  const country = COUNTRIES_LIST.find((c) => c.code === countryCode);
  if (country) {
    if (country.defaultCurrency) form.baseCurrencyCode = country.defaultCurrency;
    if (country.defaultTimezone) form.timezone = country.defaultTimezone;
  }
}

const selectedCountry = $derived(COUNTRIES_LIST.find((c) => c.code === form.countryCode));
const selectedTz = $derived(TIMEZONE_OPTIONS.find((t) => t.value === form.timezone));
const selectedCur = $derived(CURRENCY_OPTIONS.find((c) => c.code === form.baseCurrencyCode));
</script>

<div class="space-y-6 max-w-3xl mx-auto py-1">
  <div class="space-y-1 text-start">
    <div class="flex items-center gap-2">
      <span class="text-xs font-semibold text-primary uppercase font-mono tracking-wider">
        {isRTL ? "المرحلة ٣ من ٥" : "Step 3 of 5"}
      </span>
    </div>
    <h2 class="text-xl font-bold tracking-tight text-foreground">
      {isRTL ? "بيانات المنشأة والهوية الأكاديمية" : "Organization Profile & Identity"}
    </h2>
    <p class="text-xs text-muted-foreground">
      {isRTL
        ? "حدد الاسم الرسمي، المسار التعليمي، العملة الأساسية، وبيانات الترخيص للمؤسسة."
        : "Configure your official name, educational track, base currency, and institutional licensing."}
    </p>
  </div>

  <Card class="border-border/60 shadow-md bg-card/95">
    <CardContent class="p-6 space-y-6 text-start">
      <!-- 1. Names Section -->
      <div class="space-y-3">
        <div class="flex items-center justify-between border-b border-border/40 pb-2">
          <span class="text-xs font-bold uppercase tracking-wider text-foreground font-mono flex items-center gap-1.5">
            <Building size={13} class="text-primary" />
            <span>{isRTL ? "الاسم الرسمي والتعريب" : "Official Institution Names"}</span>
          </span>
          <span class="text-[11px] text-muted-foreground font-mono">* Required</span>
        </div>

        <div class="grid grid-cols-1 sm:grid-cols-2 gap-4">
          <div class="space-y-1.5">
            <Label for="org-name-ar" class="text-xs font-medium text-foreground">
              {isRTL ? "اسم المنشأة (بالعربية) *" : "Organization Name (Arabic) *"}
            </Label>
            <Input
              id="org-name-ar"
              type="text"
              dir="rtl"
              placeholder="مثال: مدارس النور الأهلية"
              bind:value={form.organizationNameAr}
              class="h-9 text-xs"
            />
            {#if errors.organizationNameAr}
              <p class="text-[11px] text-destructive">{errors.organizationNameAr}</p>
            {/if}
          </div>

          <div class="space-y-1.5">
            <Label for="org-name-en" class="text-xs font-medium text-foreground">
              {isRTL ? "اسم المنشأة (بالإنجليزية) *" : "Organization Name (English) *"}
            </Label>
            <Input
              id="org-name-en"
              type="text"
              placeholder="e.g. Al-Noor Academy"
              bind:value={form.organizationName}
              class="h-9 text-xs"
            />
            {#if errors.organizationName}
              <p class="text-[11px] text-destructive">{errors.organizationName}</p>
            {/if}
          </div>
        </div>

        <!-- Short Code -->
        <div class="pt-1 max-w-xs">
          <div class="space-y-1.5">
            <Label for="org-code" class="text-xs font-medium text-foreground">
              {isRTL ? "رمز المؤسسة الأكاديمي المختصر" : "Organization Short Code"}
            </Label>
            <Input
              id="org-code"
              type="text"
              placeholder="e.g. NOOR-01"
              bind:value={form.organizationCode}
              class="h-9 text-xs font-mono uppercase"
            />
          </div>
        </div>
      </div>

      <!-- 2. Academic Track & Capacity Size -->
      <div class="space-y-3 pt-2">
        <div class="flex items-center justify-between border-b border-border/40 pb-2">
          <span class="text-xs font-bold uppercase tracking-wider text-foreground font-mono flex items-center gap-1.5">
            <Tag size={13} class="text-primary" />
            <span>{isRTL ? "المسار التعليمي وحجم المؤسسة" : "Academic Track & Institution Size"}</span>
          </span>
        </div>

        <div class="grid grid-cols-1 sm:grid-cols-2 gap-4">
          <!-- Educational Track -->
          <div class="space-y-1.5">
            <Label class="text-xs font-medium text-foreground">
              {isRTL ? "المسار التعليمي والمنهج *" : "Educational Track *"}
            </Label>
            <Select
              type="single"
              value={form.educationalTrack}
              onValueChange={(v) => (form.educationalTrack = v ?? "national")}
            >
              <SelectTrigger class="w-full h-9 text-xs">
                {EDUCATIONAL_TRACK_OPTIONS.find((t) => t.value === form.educationalTrack)?.labelAr || form.educationalTrack}
              </SelectTrigger>
              <SelectContent>
                {#each EDUCATIONAL_TRACK_OPTIONS as track}
                  <SelectItem value={track.value}>
                    <div class="space-y-0.5">
                      <div class="font-medium text-xs">{isRTL ? track.labelAr : track.labelEn}</div>
                      <div class="text-[10px] text-muted-foreground">{track.badge}</div>
                    </div>
                  </SelectItem>
                {/each}
              </SelectContent>
            </Select>
          </div>

          <!-- Capacity Size -->
          <div class="space-y-1.5">
            <Label class="text-xs font-medium text-foreground">
              {isRTL ? "الطاقة الاستيعابية التقديرية" : "Estimated Institution Capacity"}
            </Label>
            <Select
              type="single"
              value={form.organizationSize}
              onValueChange={(v) => (form.organizationSize = v ?? "medium")}
            >
              <SelectTrigger class="w-full h-9 text-xs">
                {ORGANIZATION_SIZE_OPTIONS.find((s) => s.value === form.organizationSize)?.labelAr || form.organizationSize}
              </SelectTrigger>
              <SelectContent>
                {#each ORGANIZATION_SIZE_OPTIONS as size}
                  <SelectItem value={size.value}>
                    {isRTL ? size.labelAr : size.labelEn}
                  </SelectItem>
                {/each}
              </SelectContent>
            </Select>
          </div>
        </div>
      </div>

      <!-- 3. Regional Settings (Country, City, Currency, Timezone) -->
      <div class="space-y-3 pt-2">
        <div class="flex items-center justify-between border-b border-border/40 pb-2">
          <span class="text-xs font-bold uppercase tracking-wider text-foreground font-mono flex items-center gap-1.5">
            <span>{isRTL ? "البيئة الإقليمية والعملة" : "Regional Localization & Base Currency"}</span>
          </span>
        </div>

        <div class="grid grid-cols-1 sm:grid-cols-2 gap-4">
          <!-- Country -->
          <div class="space-y-1.5">
            <Label class="text-xs font-medium text-foreground">
              {isRTL ? "الدولة والمنطقة *" : "Country *"}
            </Label>
            <Select
              type="single"
              value={form.countryCode}
              onValueChange={(v) => selectCountry(v ?? "SA")}
            >
              <SelectTrigger class="w-full h-9 text-xs">
                {selectedCountry ? `${selectedCountry.flag} ${isRTL ? selectedCountry.nameAr : selectedCountry.nameEn}` : form.countryCode}
              </SelectTrigger>
              <SelectContent>
                {#each COUNTRIES_LIST as country}
                  <SelectItem value={country.code}>
                    {country.flag} {isRTL ? country.nameAr : country.nameEn}
                  </SelectItem>
                {/each}
              </SelectContent>
            </Select>
          </div>

          <!-- City -->
          <div class="space-y-1.5">
            <Label for="org-city" class="text-xs font-medium text-foreground">
              {isRTL ? "المدينة / المقر الرئيسي" : "City / Campus Location"}
            </Label>
            <Input
              id="org-city"
              type="text"
              placeholder={isRTL ? "مثال: الرياض" : "e.g. Riyadh"}
              bind:value={form.city}
              class="h-9 text-xs"
            />
          </div>
        </div>

        <div class="grid grid-cols-1 sm:grid-cols-2 gap-4 pt-1">
          <!-- Timezone -->
          <div class="space-y-1.5">
            <Label class="text-xs font-medium text-foreground flex items-center gap-1">
              <Clock size={11} />
              <span>{isRTL ? "المنطقة الزمنية *" : "Timezone *"}</span>
            </Label>
            <Select
              type="single"
              value={form.timezone}
              onValueChange={(v) => (form.timezone = v ?? "Asia/Riyadh")}
            >
              <SelectTrigger class="w-full h-9 text-xs">
                {selectedTz ? `${isRTL ? selectedTz.labelAr : selectedTz.labelEn} (${selectedTz.offset})` : form.timezone}
              </SelectTrigger>
              <SelectContent>
                {#each TIMEZONE_OPTIONS as tz}
                  <SelectItem value={tz.value}>
                    {isRTL ? tz.labelAr : tz.labelEn} ({tz.offset})
                  </SelectItem>
                {/each}
              </SelectContent>
            </Select>
          </div>

          <!-- Currency -->
          <div class="space-y-1.5">
            <Label class="text-xs font-medium text-foreground flex items-center gap-1">
              <CreditCard size={11} />
              <span>{isRTL ? "العملة الأساسية للحسابات *" : "Base Accounting Currency *"}</span>
            </Label>
            <Select
              type="single"
              value={form.baseCurrencyCode}
              onValueChange={(v) => (form.baseCurrencyCode = v ?? "SAR")}
            >
              <SelectTrigger class="w-full h-9 text-xs">
                {selectedCur ? `${selectedCur.flag} ${selectedCur.code} - ${isRTL ? selectedCur.nameAr : selectedCur.nameEn}` : form.baseCurrencyCode}
              </SelectTrigger>
              <SelectContent>
                {#each CURRENCY_OPTIONS as cur}
                  <SelectItem value={cur.code}>
                    {cur.flag} {cur.code} — {isRTL ? cur.nameAr : cur.nameEn} ({cur.symbolAr})
                  </SelectItem>
                {/each}
              </SelectContent>
            </Select>
          </div>
        </div>

        <div class="pt-2 flex items-center gap-2">
          <Checkbox bind:checked={form.isHijriEnabled} id="org-hijri" />
          <Label for="org-hijri" class="text-xs font-normal text-foreground cursor-pointer">
            {isRTL ? "تفعيل التقويم الهجري المزدوج (عرض التاريخ الهجري جنباً إلى جنب مع الميلادي)" : "Enable Dual Hijri Calendar (Display Hijri alongside Gregorian)"}
          </Label>
        </div>
      </div>

      <!-- 4. Legal & Contact Info -->
      <div class="space-y-3 pt-2">
        <div class="flex items-center justify-between border-b border-border/40 pb-2">
          <span class="text-xs font-bold uppercase tracking-wider text-foreground font-mono flex items-center gap-1.5">
            <span>{isRTL ? "بيانات الترخيص والتواصل الرسمي" : "Licensing & Official Contact"}</span>
          </span>
        </div>

        <div class="grid grid-cols-1 sm:grid-cols-2 gap-4">
          <div class="space-y-1.5">
            <Label for="org-license" class="text-xs font-medium text-foreground">
              {isRTL ? "رقم الترخيص الوزاري / المؤسسي" : "Ministry / Institutional License No."}
            </Label>
            <Input
              id="org-license"
              type="text"
              placeholder="e.g. LIC-2026-9810"
              bind:value={form.licenseNumber}
              class="h-9 text-xs font-mono"
            />
          </div>

          <div class="space-y-1.5">
            <Label for="org-tax" class="text-xs font-medium text-foreground">
              {isRTL ? "الرقم الضريبي / السجل التجاري" : "Tax Registration / VAT ID"}
            </Label>
            <Input
              id="org-tax"
              type="text"
              placeholder="e.g. 300123456700003"
              bind:value={form.taxId}
              class="h-9 text-xs font-mono"
            />
          </div>
        </div>

        <div class="grid grid-cols-1 sm:grid-cols-2 gap-4 pt-1">
          <div class="space-y-1.5">
            <Label for="org-phone" class="text-xs font-medium text-foreground">
              {isRTL ? "هاتف المنشأة الرسمي" : "Official Phone / WhatsApp"}
            </Label>
            <Input
              id="org-phone"
              type="tel"
              placeholder="+966 11 XXX XXXX"
              bind:value={form.phone}
              class="h-9 text-xs font-mono"
            />
          </div>

          <div class="space-y-1.5">
            <Label for="org-web" class="text-xs font-medium text-foreground">
              {isRTL ? "الموقع الإلكتروني الرسمي" : "Official Website"}
            </Label>
            <Input
              id="org-web"
              type="url"
              placeholder="https://institution.edu.sa"
              bind:value={form.website}
              class="h-9 text-xs font-mono"
            />
          </div>
        </div>
      </div>

      <!-- 5. Branding Color Themes -->
      <div class="space-y-2.5 pt-2">
        <div class="flex items-center justify-between border-b border-border/40 pb-2">
          <span class="text-xs font-bold uppercase tracking-wider text-foreground font-mono flex items-center gap-1.5">
            <span>{isRTL ? "السمة اللونية وهوية العلامة" : "Brand Primary Theme Palette"}</span>
          </span>
        </div>

        <div class="flex items-center gap-2.5 flex-wrap pt-1">
          {#each COLOR_PRESETS as preset}
            {@const isSelected = form.primaryColor.toLowerCase() === preset.hex.toLowerCase()}
            <button
              type="button"
              onclick={() => (form.primaryColor = preset.hex)}
              class="size-8 rounded-full flex items-center justify-center transition-transform cursor-pointer border-2 {isSelected
                ? 'scale-110 border-foreground shadow-md ring-2 ring-primary/30'
                : 'border-transparent hover:scale-105'}"
              style="background-color: {preset.hex};"
              title={isRTL ? preset.labelAr : preset.labelEn}
            >
              {#if isSelected}
                <Check size={14} class="text-white" strokeWidth={3} />
              {/if}
            </button>
          {/each}

          <div class="ms-auto flex items-center gap-2">
            <Input
              type="color"
              bind:value={form.primaryColor}
              class="size-8 p-0 border border-border/60 rounded-full cursor-pointer"
            />
            <span class="text-xs font-mono text-muted-foreground uppercase">{form.primaryColor}</span>
          </div>
        </div>
      </div>
    </CardContent>
  </Card>
</div>
