/// Provisions the complete master report catalog into the database.
pub async fn provision_master_report_definitions<C: ConnectionTrait>(
    db: &C,
    org_id: Uuid,
    now: &str,
) -> Result<(), DomainError> {
    let catalog = get_master_report_catalog();
    info!(
        "Provisioning master business report catalog ({} reports) for org_id={}",
        catalog.len(),
        org_id
    );

    for (idx, entry) in catalog.into_iter().enumerate() {
        let rid = Uuid::new_v4();
        db.execute(Statement::from_sql_and_values(
            db.get_database_backend(),
            "INSERT INTO report_definitions (id, org_id, code, name, name_ar, domain, category, description, description_ar, parameters_json, required_permissions, supported_formats, data_provider_key, is_system, is_active, sort_order, version, created_at, updated_at) \
             SELECT $1, $2, $3, $4, $5, $6, $7, $8, $9, '[]', '[]', '[\"PDF\",\"CSV\",\"XLSX\",\"HTML\"]', $10, 1, 1, $11, 1, $12, $13 \
             WHERE NOT EXISTS (SELECT 1 FROM report_definitions WHERE org_id = $2 AND code = $3)",
            vec![
                rid.into(), org_id.into(), entry.code.into(),
                entry.name.into(), entry.name_ar.into(), entry.domain.into(), entry.category.into(),
                entry.description.into(), entry.description_ar.into(), entry.provider_key.into(),
                (idx as i32).into(),
                now.to_string().into(), now.to_string().into()
            ]
        )).await.ok();
    }

    Ok(())
}
