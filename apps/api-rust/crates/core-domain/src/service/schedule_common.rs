use chrono::Utc;
use infra_scheduler::RoomDto;
use uuid::Uuid;

use crate::entities::{room, scheduled_lesson};
use crate::service::schedule::{ScheduleConflict, CreateLessonRequest};

/// Shared placement input — used by manual CRUD and solver apply (single code path).
#[derive(Clone, Debug)]
pub struct LessonPlacement {
    pub cycle_id: String,
    pub class_id: String,
    pub class_subject_id: String,
    pub subject_id: String,
    pub teacher_id: String,
    pub time_slot_id: String,
    pub day_of_week: i32,
    pub room_id: Option<String>,
    pub topic: Option<String>,
    pub topic_ar: Option<String>,
    pub homework: Option<String>,
    pub notes: Option<String>,
}

impl LessonPlacement {
    pub fn from_create_request(req: CreateLessonRequest, class_subject_id: String) -> Self {
        Self {
            cycle_id: req.cycle_id,
            class_id: req.class_id,
            class_subject_id,
            subject_id: req.subject_id,
            teacher_id: req.teacher_id,
            time_slot_id: req.time_slot_id,
            day_of_week: req.day_of_week,
            room_id: req.room_id,
            topic: req.topic,
            topic_ar: req.topic_ar,
            homework: req.homework,
            notes: req.notes,
        }
    }

    pub fn from_solver_assignment(
        cycle_id: &str,
        assignment: &infra_scheduler::LessonAssignmentDto,
        job_id: &str,
    ) -> Option<Self> {
        let time_slot_id = assignment.time_slot_id.clone()?;
        let day_of_week = assignment.day_of_week?;
        Some(Self {
            cycle_id: cycle_id.to_string(),
            class_id: assignment.class_id.clone(),
            class_subject_id: assignment.class_subject_id.clone(),
            subject_id: assignment.subject_id.clone(),
            teacher_id: assignment.teacher_id.clone(),
            time_slot_id,
            day_of_week,
            room_id: assignment.room_id.clone(),
            topic: None,
            topic_ar: None,
            homework: None,
            notes: Some(format!("auto-generated by solve job {job_id}")),
        })
    }
}

pub fn room_entity_to_dto(r: &room::Model) -> RoomDto {
    RoomDto {
        id: r.id.clone(),
        name: r.name.clone(),
        capacity: r.capacity,
        room_type: r.room_type.clone(),
    }
}

pub fn classify_conflict_type(
    lesson: &scheduled_lesson::Model,
    teacher_id: &str,
    class_id: &str,
) -> &'static str {
    if lesson.teacher_id == teacher_id {
        "teacher"
    } else if lesson.class_id == class_id {
        "class"
    } else {
        "room"
    }
}

pub fn map_lesson_conflicts(
    conflicts: Vec<scheduled_lesson::Model>,
    teacher_id: &str,
    class_id: &str,
) -> Vec<ScheduleConflict> {
    conflicts
        .into_iter()
        .map(|c| {
            let conflict_type = classify_conflict_type(&c, teacher_id, class_id);
            let lesson_id = c.id.clone();
            ScheduleConflict {
                lesson_id,
                conflict_type: conflict_type.to_string(),
                message: format!("Conflict with lesson {} ({})", c.id, conflict_type),
            }
        })
        .collect()
}

impl super::Service {
    /// Single insertion path: conflict check → persist (room name resolved on read via rooms table).
    pub(crate) async fn persist_lesson(
        &self,
        org_id: &str,
        placement: LessonPlacement,
        exclude_id: Option<&str>,
    ) -> Result<scheduled_lesson::Model, String> {
        let conflicts = self
            .repo
            .find_lesson_conflicts(
                org_id,
                &placement.cycle_id,
                &placement.time_slot_id,
                placement.day_of_week,
                exclude_id,
                &placement.teacher_id,
                &placement.class_id,
                placement.room_id.as_deref(),
            )
            .await
            .map_err(|e| e.to_string())?;

        if !conflicts.is_empty() {
            let mapped = map_lesson_conflicts(conflicts, &placement.teacher_id, &placement.class_id);
            return Err(format!("schedule conflict: {}", mapped[0].message));
        }

        if let Some(rid) = &placement.room_id {
            let exists = self
                .repo
                .get_room_by_id(rid)
                .await
                .map_err(|e| e.to_string())?
                .is_some();
            if !exists {
                return Err(format!("room not found: {rid}"));
            }
        }

        let now = Utc::now().to_rfc3339();
        let lesson = scheduled_lesson::Model {
            id: Uuid::new_v4().to_string(),
            org_id: org_id.to_string(),
            cycle_id: placement.cycle_id,
            class_id: placement.class_id,
            class_subject_id: placement.class_subject_id,
            subject_id: placement.subject_id,
            teacher_id: placement.teacher_id,
            substitute_teacher_id: None,
            time_slot_id: placement.time_slot_id,
            day_of_week: placement.day_of_week,
            room_id: placement.room_id,
            room_name: None,
            status: "scheduled".to_string(),
            is_substituted: 0,
            substitution_reason: None,
            topic: placement.topic,
            topic_ar: placement.topic_ar,
            objectives: None,
            materials: None,
            homework: placement.homework,
            homework_due_date: None,
            attendance_taken: 0,
            attendance_taken_at: None,
            attendance_taken_by: None,
            attendance_method: None,
            notes: placement.notes,
            cancellation_reason: None,
            created_at: now.clone(),
            updated_at: now,
        };

        self.repo
            .insert_scheduled_lesson(lesson)
            .await
            .map_err(|e| e.to_string())
    }
}
