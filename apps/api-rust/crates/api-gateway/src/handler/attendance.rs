#[utoipa::path(get, path = "/api/attendance/report/{class_id}")]
pub async fn get_attendance_report(State(state): State<AppState>, Path(class_id): Path<String>, AuthenticatedUser(user): AuthenticatedUser, Json(body): Json<serde_json::Value>) -> Result<impl IntoResponse, (StatusCode, Json<serde_json::Value>)> {
    let ctx = state.build_context(&user.org_id, &user.id);
    let start = body["start"].as_str().unwrap_or_default();
    let end = body["end"].as_str().unwrap_or_default();
    let r = ops::attendance::report(&ctx, &class_id, start, end).await.map_err(|e| (StatusCode::INTERNAL_SERVER_ERROR, Json(json!({"success":false,"error":e.to_string()}))))?;
    ok!(r)
}
