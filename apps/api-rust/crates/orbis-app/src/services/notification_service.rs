use chrono::Utc;
use orbis_domain::entities::notification::Notification;
use orbis_domain::entities::notification_preference::UserNotificationPreference;
use orbis_domain::errors::DomainError;
use orbis_domain::events::DomainEvent;
use serde::{Deserialize, Serialize};
use std::sync::Arc;
use uuid::Uuid;

use crate::context::RequestContext;
use crate::ports::iam::PermissionCheckerPort;
use crate::ports::repositories::{
    NotificationFilter, NotificationPreferenceRepository, NotificationRepository,
};

// ─── Inputs ────────────────────────────────────────────────────

/// Input for creating a notification from a domain event.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CreateNotificationInput {
    pub org_id: Uuid,
    pub recipient_user_id: Uuid,
    pub category: String,
    pub priority: String,
    pub title: String,
    pub title_ar: Option<String>,
    pub body: String,
    pub body_ar: Option<String>,
    pub entity_type: Option<String>,
    pub entity_id: Option<Uuid>,
    pub action_route: Option<String>,
    pub source_event: String,
    pub correlation_id: String,
    pub expires_at: Option<chrono::DateTime<Utc>>,
}

/// Response DTO for unread count.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct UnreadCountResponse {
    pub count: i64,
}

// ─── Service ───────────────────────────────────────────────────

pub struct NotificationService {
    pub notification_repo: Arc<dyn NotificationRepository>,
    pub preference_repo: Arc<dyn NotificationPreferenceRepository>,
    pub permission_checker: Arc<dyn PermissionCheckerPort>,
    pub broadcast_tx: Option<tokio::sync::broadcast::Sender<Notification>>,
}

impl NotificationService {
    pub fn new(
        notification_repo: Arc<dyn NotificationRepository>,
        preference_repo: Arc<dyn NotificationPreferenceRepository>,
        permission_checker: Arc<dyn PermissionCheckerPort>,
    ) -> Self {
        Self {
            notification_repo,
            preference_repo,
            permission_checker,
            broadcast_tx: None,
        }
    }

    pub fn with_broadcaster(mut self, tx: tokio::sync::broadcast::Sender<Notification>) -> Self {
        self.broadcast_tx = Some(tx);
        self
    }

    // ── Create ─────────────────────────────────────────────────

    /// Create a notification from a domain event.
    ///
    /// Deduplicates by `correlation_id` — if a notification with the same
    /// correlation_id already exists, this is a no-op and returns the existing one.
    ///
    /// This method does NOT require a `RequestContext` because notifications are
    /// typically generated by system processes (event handlers, autopilot, workflows)
    /// rather than direct user API calls.
    pub async fn create(
        &self,
        input: CreateNotificationInput,
    ) -> Result<Notification, DomainError> {
        // ── Deduplication ──────────────────────────────────────
        if let Some(existing) = self
            .notification_repo
            .find_by_correlation_id(&input.correlation_id)
            .await?
        {
            return Ok(existing);
        }

        // ── Check user preference ──────────────────────────────
        let prefs = self
            .preference_repo
            .find_for_user(input.org_id, input.recipient_user_id)
            .await?;

        let in_app_enabled = prefs
            .iter()
            .find(|p| p.category == input.category)
            .map(|p| p.in_app_enabled)
            .unwrap_or(true); // default: enabled

        if !in_app_enabled {
            // User has explicitly disabled in-app notifications for this category.
            // Return a "virtual" notification (not persisted) so callers don't error.
            let notification = Notification {
                id: Uuid::new_v4(),
                org_id: input.org_id,
                recipient_user_id: input.recipient_user_id,
                category: input.category,
                priority: input.priority,
                title: input.title,
                title_ar: input.title_ar,
                body: input.body,
                body_ar: input.body_ar,
                entity_type: input.entity_type,
                entity_id: input.entity_id,
                action_route: input.action_route,
                source_event: input.source_event,
                correlation_id: input.correlation_id,
                schema_version: 1,
                is_read: true,
                read_at: Some(Utc::now()),
                is_dismissed: true,
                dismissed_at: Some(Utc::now()),
                expires_at: input.expires_at,
                created_at: Utc::now(),
            };
            return Ok(notification);
        }

        // ── Persist ────────────────────────────────────────────
        let notification = Notification {
            id: Uuid::new_v4(),
            org_id: input.org_id,
            recipient_user_id: input.recipient_user_id,
            category: input.category,
            priority: input.priority,
            title: input.title,
            title_ar: input.title_ar,
            body: input.body,
            body_ar: input.body_ar,
            entity_type: input.entity_type,
            entity_id: input.entity_id,
            action_route: input.action_route,
            source_event: input.source_event,
            correlation_id: input.correlation_id,
            schema_version: 1,
            is_read: false,
            read_at: None,
            is_dismissed: false,
            dismissed_at: None,
            expires_at: input.expires_at,
            created_at: Utc::now(),
        };

        self.notification_repo.save(&notification).await?;

        if let Some(tx) = &self.broadcast_tx {
            let _ = tx.send(notification.clone());
        }

        Ok(notification)
    }

    // ── Read ───────────────────────────────────────────────────

    /// List notifications for the authenticated user.
    pub async fn list(
        &self,
        ctx: &RequestContext,
        filter: &NotificationFilter,
    ) -> Result<Vec<Notification>, DomainError> {
        let user_id = ctx
            .user_id()
            .ok_or_else(|| DomainError::Unauthorized("User context required".into()))?;

        self.notification_repo
            .list_for_user(ctx.tenant_id, user_id, filter)
            .await
    }

    /// Get unread count for the authenticated user.
    pub async fn unread_count(&self, ctx: &RequestContext) -> Result<i64, DomainError> {
        let user_id = ctx
            .user_id()
            .ok_or_else(|| DomainError::Unauthorized("User context required".into()))?;

        self.notification_repo
            .count_unread(ctx.tenant_id, user_id)
            .await
    }

    // ── Update ─────────────────────────────────────────────────

    /// Mark a single notification as read.
    pub async fn mark_read(
        &self,
        ctx: &RequestContext,
        notification_id: Uuid,
    ) -> Result<(), DomainError> {
        let _user_id = ctx
            .user_id()
            .ok_or_else(|| DomainError::Unauthorized("User context required".into()))?;

        // Verify notification belongs to this org
        let notification = self
            .notification_repo
            .find_by_id(ctx.tenant_id, notification_id)
            .await?
            .ok_or_else(|| DomainError::NotFound("Notification not found".into()))?;

        // Verify the notification belongs to the requesting user
        if notification.recipient_user_id != _user_id {
            return Err(DomainError::Forbidden(
                "Cannot mark another user's notification as read".into(),
            ));
        }

        self.notification_repo
            .mark_read(ctx.tenant_id, notification_id)
            .await
    }

    /// Mark all notifications as read for the authenticated user.
    pub async fn mark_all_read(&self, ctx: &RequestContext) -> Result<u64, DomainError> {
        let user_id = ctx
            .user_id()
            .ok_or_else(|| DomainError::Unauthorized("User context required".into()))?;

        self.notification_repo
            .mark_all_read(ctx.tenant_id, user_id)
            .await
    }

    /// Dismiss (soft-delete) a notification.
    pub async fn dismiss(
        &self,
        ctx: &RequestContext,
        notification_id: Uuid,
    ) -> Result<(), DomainError> {
        let user_id = ctx
            .user_id()
            .ok_or_else(|| DomainError::Unauthorized("User context required".into()))?;

        let notification = self
            .notification_repo
            .find_by_id(ctx.tenant_id, notification_id)
            .await?
            .ok_or_else(|| DomainError::NotFound("Notification not found".into()))?;

        if notification.recipient_user_id != user_id {
            return Err(DomainError::Forbidden(
                "Cannot dismiss another user's notification".into(),
            ));
        }

        self.notification_repo
            .dismiss(ctx.tenant_id, notification_id)
            .await
    }

    // ── Preferences ────────────────────────────────────────────

    /// Get the authenticated user's notification preferences.
    pub async fn get_preferences(
        &self,
        ctx: &RequestContext,
    ) -> Result<Vec<UserNotificationPreference>, DomainError> {
        let user_id = ctx
            .user_id()
            .ok_or_else(|| DomainError::Unauthorized("User context required".into()))?;

        self.preference_repo
            .find_for_user(ctx.tenant_id, user_id)
            .await
    }

    /// Update the authenticated user's notification preferences.
    pub async fn update_preferences(
        &self,
        ctx: &RequestContext,
        preferences: Vec<UserNotificationPreference>,
    ) -> Result<Vec<UserNotificationPreference>, DomainError> {
        let user_id = ctx
            .user_id()
            .ok_or_else(|| DomainError::Unauthorized("User context required".into()))?;

        // Ensure all preferences belong to the requesting user/org
        for pref in &preferences {
            if pref.user_id != user_id || pref.org_id != ctx.tenant_id {
                return Err(DomainError::Forbidden(
                    "Cannot update another user's preferences".into(),
                ));
            }
        }

        self.preference_repo
            .save_all(ctx.tenant_id, user_id, &preferences)
            .await?;

        self.preference_repo
            .find_for_user(ctx.tenant_id, user_id)
            .await
    }

    // ── Maintenance ────────────────────────────────────────────

    /// Delete expired notifications. Intended to be called by a background job.
    pub async fn cleanup_expired(&self) -> Result<u64, DomainError> {
        self.notification_repo.delete_expired().await
    }

    // ── Domain Event Handling ──────────────────────────────────

    /// Automatically react to system domain events and dispatch notifications.
    pub async fn handle_domain_event(
        &self,
        ctx: &RequestContext,
        event: &DomainEvent,
    ) -> Result<(), DomainError> {
        let recipient_user_id = match ctx.actor {
            orbis_domain::iam::actor::Actor::User(uid) => uid,
            _ => return Ok(()),
        };

        match event {
            DomainEvent::GradeRecorded {
                grade_id,
                student_id,
                score,
                ..
            } => {
                let _ = self
                    .create(CreateNotificationInput {
                        org_id: ctx.tenant_id,
                        recipient_user_id,
                        category: "grades".to_string(),
                        priority: "normal".to_string(),
                        title: "Grade Published".to_string(),
                        title_ar: Some("تم نشر درجة جديدة".to_string()),
                        body: format!("A grade of {} was recorded.", score),
                        body_ar: Some(format!("تم تسجيل درجة جديدة: {}.", score)),
                        entity_type: Some("student".to_string()),
                        entity_id: Some(*student_id),
                        action_route: Some(format!("/(app)/student/{}", student_id)),
                        source_event: "GradeRecorded".to_string(),
                        correlation_id: format!("grade-recorded-{}", grade_id),
                        expires_at: None,
                    })
                    .await;
            }
            DomainEvent::AttendanceMarked {
                attendance_id,
                student_id,
                status,
                ..
            } => {
                if status.eq_ignore_ascii_case("absent") || status.eq_ignore_ascii_case("late") {
                    let _ = self
                        .create(CreateNotificationInput {
                            org_id: ctx.tenant_id,
                            recipient_user_id,
                            category: "attendance".to_string(),
                            priority: "high".to_string(),
                            title: format!("Attendance Alert: {}", status),
                            title_ar: Some(format!("تنبيه حضور: {}", status)),
                            body: format!("Attendance status was marked as {}.", status),
                            body_ar: Some(format!("تم تسجيل حالة الحضور كـ {}.", status)),
                            entity_type: Some("student".to_string()),
                            entity_id: Some(*student_id),
                            action_route: Some(format!("/(app)/student/{}", student_id)),
                            source_event: "AttendanceMarked".to_string(),
                            correlation_id: format!("attendance-marked-{}", attendance_id),
                            expires_at: None,
                        })
                        .await;
                }
            }
            DomainEvent::BehaviorLogged {
                record_id,
                student_id,
                record_type,
                points,
                ..
            } => {
                let _ = self
                    .create(CreateNotificationInput {
                        org_id: ctx.tenant_id,
                        recipient_user_id,
                        category: "behavior".to_string(),
                        priority: "normal".to_string(),
                        title: "Behavior Incident Logged".to_string(),
                        title_ar: Some("تسجيل ملاحظة سلوكية".to_string()),
                        body: format!(
                            "A {} note with {} points was recorded.",
                            record_type, points
                        ),
                        body_ar: Some(format!(
                            "تم تسجيل ملاحظة سلوكية: {} ({} نقطة).",
                            record_type, points
                        )),
                        entity_type: Some("student".to_string()),
                        entity_id: Some(*student_id),
                        action_route: Some(format!("/(app)/student/{}", student_id)),
                        source_event: "BehaviorLogged".to_string(),
                        correlation_id: format!("behavior-logged-{}", record_id),
                        expires_at: None,
                    })
                    .await;
            }
            DomainEvent::StudentEnrolled {
                enrollment_id,
                student_id,
                org_id,
                ..
            } => {
                let _ = self
                    .create(CreateNotificationInput {
                        org_id: *org_id,
                        recipient_user_id,
                        category: "enrollment".to_string(),
                        priority: "normal".to_string(),
                        title: "Student Enrolled".to_string(),
                        title_ar: Some("تم تسجيل الطالب".to_string()),
                        body: "Student enrollment was confirmed.".to_string(),
                        body_ar: Some("تم تأكيد تسجيل الطالب بنجاح.".to_string()),
                        entity_type: Some("student".to_string()),
                        entity_id: Some(*student_id),
                        action_route: Some(format!("/(app)/student/{}", student_id)),
                        source_event: "StudentEnrolled".to_string(),
                        correlation_id: format!("student-enrolled-{}", enrollment_id),
                        expires_at: None,
                    })
                    .await;
            }
            DomainEvent::CohortPromoted {
                job_id,
                org_id,
                promoted_count,
                ..
            } => {
                let _ = self
                    .create(CreateNotificationInput {
                        org_id: *org_id,
                        recipient_user_id,
                        category: "approval".to_string(),
                        priority: "high".to_string(),
                        title: "Cohort Promoted".to_string(),
                        title_ar: Some("ترقية الدفعة".to_string()),
                        body: format!("{} students were successfully promoted.", promoted_count),
                        body_ar: Some(format!("تمت ترقية {} طالباً بنجاح.", promoted_count)),
                        entity_type: None,
                        entity_id: None,
                        action_route: None,
                        source_event: "CohortPromoted".to_string(),
                        correlation_id: format!("cohort-promoted-{}", job_id),
                        expires_at: None,
                    })
                    .await;
            }
            _ => {}
        }

        Ok(())
    }
}
